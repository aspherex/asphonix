// Splits SoniX's inline SVG sprite (src/assets/icons/sprite.svg) into one SVG per icon
// under assets/icons/ and writes crates/sonix-ui/src/icons_gen.rs (name -> include_bytes!).
// Usage: node scripts/gen-icons.mjs <path-to-SoniX>/src/assets/icons/sprite.svg
import fs from "node:fs";
const src = fs.readFileSync(process.argv[2], "utf8");
const re = /<symbol id="icon-([a-z0-9-]+)" viewBox="([^"]+)">([\s\S]*?)<\/symbol>/g;
const names = [];
let m;
while ((m = re.exec(src))) {
  const [, name, vb, inner] = m;
  const body = inner.replace(/currentColor/g, "#ffffff").trim().replace(/\n\s*/g, "");
  fs.writeFileSync(`assets/icons/${name}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}">${body}</svg>\n`);
  names.push(name);
}
const rs = `// @generated by scripts/gen-icons.mjs, do not edit.\npub fn icon(path: &str) -> Option<&'static [u8]> {\n    match path {\n${names
  .map((n) => `        "icons/${n}.svg" => Some(include_bytes!("../../../assets/icons/${n}.svg")),\n`)
  .join("")}        _ => None,\n    }\n}\n`;
fs.writeFileSync("crates/sonix-ui/src/icons_gen.rs", rs);
console.log(names.length + " icons");
