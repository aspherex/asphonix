//! Generates the `Key` enum from `locales/en/sonix.ftl` (the source locale): one variant per message id, in file
//! order (`nav-home` -> `Key::NavHome`), plus the id and the variable names (`$count`) of every message. A key that
//! is not in the English file is therefore a compile error, not a runtime miss.
use std::fmt::Write as _;
use std::path::Path;

/// `(id, variables)` of every message of a Fluent file. Only what the generator needs: a message starts at column 0
/// with an identifier followed by `=`; other non-empty lines continue it; `#` comments and `-terms` end it.
fn messages(src: &str) -> Vec<(String, Vec<String>)> {
    let mut out: Vec<(String, Vec<String>)> = Vec::new();
    let mut cur: Option<usize> = None;
    for line in src.lines() {
        let starts_entry = line.chars().next().is_some_and(|c| c.is_ascii_alphabetic());
        let body = if starts_entry {
            let Some((id, rest)) = line.split_once('=') else {
                cur = None;
                continue;
            };
            out.push((id.trim().to_string(), Vec::new()));
            cur = Some(out.len() - 1);
            rest
        } else if !line.is_empty() && !line.starts_with('#') && !line.starts_with('-') {
            // indented continuation, or a select expression closing at column 0 (`} yet: ...`)
            line
        } else {
            cur = None;
            continue;
        };
        let Some(i) = cur else { continue };
        let b = body.as_bytes();
        let mut k = 0;
        while k < b.len() {
            if b[k] == b'$' {
                let s = k + 1;
                let mut e = s;
                while e < b.len() && (b[e].is_ascii_alphanumeric() || b[e] == b'_' || b[e] == b'-') {
                    e += 1;
                }
                let v = &body[s..e];
                if !v.is_empty() && !out[i].1.iter().any(|x| x == v) {
                    out[i].1.push(v.to_string());
                }
                k = e;
            } else {
                k += 1;
            }
        }
    }
    out
}

fn camel(id: &str) -> String {
    id.split(['-', '_']).filter(|p| !p.is_empty()).map(|p| {
        let mut c = p.chars();
        c.next().map(|f| f.to_ascii_uppercase().to_string() + c.as_str()).unwrap_or_default()
    }).collect()
}

fn main() {
    let en = Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("locales/en/sonix.ftl");
    println!("cargo:rerun-if-changed={}", en.display());
    println!("cargo:rerun-if-changed=locales/de/sonix.ftl");
    let src = std::fs::read_to_string(&en).expect("locales/en/sonix.ftl");
    let msgs = messages(&src);
    let mut seen = std::collections::HashSet::new();
    for (id, _) in &msgs {
        assert!(seen.insert(camel(id)), "duplicate message id (after CamelCase): {id}");
    }
    let n = msgs.len();
    let mut s = String::new();
    s.push_str("/// A message of `locales/en/sonix.ftl` (generated by build.rs).\n");
    s.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\n#[repr(u16)]\npub enum Key {\n");
    for (id, _) in &msgs {
        let _ = writeln!(s, "    /// `{id}`\n    {},", camel(id));
    }
    s.push_str("}\n\n");
    let _ = writeln!(s, "/// Number of messages.\npub const COUNT: usize = {n};");
    let _ = writeln!(s, "const IDS: [&str; COUNT] = [{}];", msgs.iter().map(|(id, _)| format!("{id:?}")).collect::<Vec<_>>().join(", "));
    let _ = writeln!(s, "const NAMES: [&str; COUNT] = [{}];", msgs.iter().map(|(id, _)| format!("{:?}", camel(id))).collect::<Vec<_>>().join(", "));
    let vars: Vec<String> = msgs.iter().map(|(_, v)| format!("&[{}]", v.iter().map(|x| format!("{x:?}")).collect::<Vec<_>>().join(", "))).collect();
    let _ = writeln!(s, "const VARS: [&[&str]; COUNT] = [{}];", vars.join(", "));
    let _ = writeln!(s, "impl Key {{\n    /// Every key, in file order.\n    pub const ALL: [Key; COUNT] = [{}];\n}}", msgs.iter().map(|(id, _)| format!("Key::{}", camel(id))).collect::<Vec<_>>().join(", "));
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("keys.rs");
    std::fs::write(out, s).unwrap();
}
